#Requires -RunAsAdministrator
<#
.SYNOPSIS
  Windows 11 Home kiosk: Edge full-screen (--kiosk) at logon, relaunched if it exits,
  plus power settings that keep the display and network awake.

.DESCRIPTION
  Run as admin while signed in as the kiosk user (Autologon from Sysinternals is
  recommended for that account):
    powershell -ExecutionPolicy Bypass -File deploy\windows\setup-kiosk.ps1 -Url http://localhost:8787/d/<token>

  Assigned Access (Windows Pro) is not needed for Windows 11 Home and is not set up here.

.PARAMETER SkipPower
  Leave powercfg settings alone.
.PARAMETER Uninstall
  Removes the logon task and the launcher script.
#>
[CmdletBinding(DefaultParameterSetName = 'Install')]
param(
  [Parameter(Mandatory = $true, ParameterSetName = 'Install')][string]$Url,
  [Parameter(ParameterSetName = 'Install')][switch]$SkipPower,
  [Parameter(Mandatory = $true, ParameterSetName = 'Uninstall')][switch]$Uninstall
)

$ErrorActionPreference = 'Stop'
$TaskName = 'Slate Kiosk'
$LauncherDir = Join-Path $env:ProgramData 'slate\kiosk'
$Launcher = Join-Path $LauncherDir 'kiosk-loop.ps1'

if ($Uninstall) {
  Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false -ErrorAction SilentlyContinue
  if (Test-Path $Launcher) { Remove-Item -Force $Launcher }
  Write-Host 'Kiosk task removed.'
  return
}

$uri = $null
if (-not [Uri]::TryCreate($Url, [UriKind]::Absolute, [ref]$uri) -or $uri.Scheme -notin 'http', 'https') {
  throw "-Url must be an http(s) address, for example http://localhost:8787/d/<token>"
}
# Both URLs go into single-quoted strings in the generated launcher.
$quote = { param($s) "'" + $s.Replace("'", "''") + "'" }
$kioskUrl = & $quote $uri.AbsoluteUri
# The server listens on IPv4; "localhost" can resolve to ::1 first and time out.
$healthHost = if ($uri.IsLoopback -and -not $uri.HostNameType.Equals([UriHostNameType]::IPv6)) { '127.0.0.1' } else { $uri.Host }
$health = & $quote ("{0}://{1}:{2}/healthz" -f $uri.Scheme, $healthHost, $uri.Port)

New-Item -ItemType Directory -Force -Path $LauncherDir | Out-Null
# install.ps1 restricts C:\ProgramData\slate to admins; the kiosk user only needs to read this.
& icacls.exe $LauncherDir /inheritance:r /grant:r '*S-1-5-18:(OI)(CI)F' '*S-1-5-32-544:(OI)(CI)F' '*S-1-5-32-545:(OI)(CI)RX' /Q | Out-Null
@"
# Generated by setup-kiosk.ps1. Waits for the Slate server, then keeps Edge in kiosk mode.
`$edge = @(
  "`${env:ProgramFiles(x86)}\Microsoft\Edge\Application\msedge.exe",
  "`$env:ProgramFiles\Microsoft\Edge\Application\msedge.exe"
) | Where-Object { Test-Path `$_ } | Select-Object -First 1
`$edgeArgs = @(
  '--kiosk', $kioskUrl, '--edge-kiosk-type=fullscreen', '--no-first-run',
  '--autoplay-policy=no-user-gesture-required', '--disable-features=Translate',
  '--kiosk-idle-timeout-minutes=0'
)
while (`$true) {
  try { Invoke-WebRequest -UseBasicParsing $health -TimeoutSec 3 | Out-Null } catch { Start-Sleep -Seconds 3; continue }
  Start-Process -FilePath `$edge -ArgumentList `$edgeArgs -Wait
  Start-Sleep -Seconds 5
}
"@ | Set-Content -Path $Launcher -Encoding UTF8

$user = "$env:USERDOMAIN\$env:USERNAME"
$action = New-ScheduledTaskAction -Execute 'powershell.exe' `
  -Argument "-NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File `"$Launcher`""
$trigger = New-ScheduledTaskTrigger -AtLogOn -User $user
$principal = New-ScheduledTaskPrincipal -UserId $user -LogonType Interactive -RunLevel Limited
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
  -ExecutionTimeLimit ([TimeSpan]::Zero) -MultipleInstances IgnoreNew
Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Principal $principal `
  -Settings $settings -Description 'Slate display: Edge kiosk' -Force | Out-Null

# Edge policies: no first-run, restore prompts, or translate bar; allow autoplay with sound.
$policy = 'HKLM:\Software\Policies\Microsoft\Edge'
New-Item -Path $policy -Force | Out-Null
foreach ($p in @(
    @{ Name = 'HideFirstRunExperience'; Value = 1 },
    @{ Name = 'TranslateEnabled'; Value = 0 },
    @{ Name = 'RestoreOnStartup'; Value = 5 },
    @{ Name = 'PasswordManagerEnabled'; Value = 0 },
    @{ Name = 'BrowserSignin'; Value = 0 },
    @{ Name = 'AutoplayAllowed'; Value = 1 }
  )) {
  New-ItemProperty -Path $policy -Name $p.Name -Value $p.Value -PropertyType DWord -Force | Out-Null
}

if (-not $SkipPower) {
  # Night mode dims in-page; the screen must stay on or Modern Standby drops Wi-Fi and the server.
  powercfg /change monitor-timeout-ac 0
  powercfg /change standby-timeout-ac 0
  powercfg /hibernate off
}

Write-Host "Kiosk set up for $user. Sign out and back in (or reboot) to start it."
Write-Host 'Reminder: enable Battery Limit in the Surface UEFI for a device that stays plugged in.'
